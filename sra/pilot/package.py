def _soglasie() -> str:
    conditions = "\n".join(f"  {n}. {c}" for n, c in enumerate(INTERVENTION_CONDITIONS, 1))
    return f"""# Согласие школы на участие в пилоте системы поддержки решений (ШАБЛОН)

> Статус документа: инженерный шаблон. Требует просмотра юристом школы или
> управления образования до подписания. Система не начинает никаких работ
> в школе до подписания этого документа (условие №1 из ворот INTERVENTION).

## 1. Стороны
Школа: ________ (далее «Школа»), в лице ________.
Оператор системы: ________ (далее «Оператор»).

## 2. Предмет
Школа соглашается на участие в проверке системы поддержки решений школьной
столовой (далее «Система»): сбор агрегированных измерений питания и отходов,
расчёт метрик/прогнозов, выработка ПРЕДЛОЖЕНИЙ. Любое изменение работы кухни
(вмешательство) — отдельное решение по порядку раздела 5.

## 3. Данные
- Собираются ТОЛЬКО агрегированные данные по приёмам пищи: массы в граммах
  (приготовлено/выдано/отходы по категориям), счётчики (питающиеся, порции),
  меню по дням. Персональные данные учеников НЕ собираются, профили учеников
  НЕ строятся (инвариант Системы).
- Каждая запись получает происхождение (кто/когда/откуда); данные
  верифицируются процедурой проверки (verification) Системы.
- Места хранения: локальное хранилище Школы/Оператора; передача третьим
  лицам — только с новым письменным согласием Школы.

## 4. Права Школы
- Отозвать согласие в любой момент письменно: данные остаются в хранилище
  с пометкой об отзыве, новый сбор прекращается.
- Запросить выгрузку всех своих данных и отчётов в машиночитаемом виде.
- Отклонить любое предложение Системы без объяснения причин.

## 5. Вмешательства — только через одобрение
Система НЕ исполняет действия сама. Порядок допуска вмешательства —
последовательное выполнение всех условий (sra/phases.py, INTERVENTION_CONDITIONS):
{conditions}

До выполнения ВСЕХ условий Система возвращает решение NO_CHANGE
(«изменений не требуется/невозможно безопасно предложить») с указанием
недостающих условий. NO_CHANGE не подтверждает безопасность текущей практики.

## 6. Ответственность и сроки
- Сроки пилота: ____ недель (минимум по плану оценки эффекта — см. файл
  04-plan-ocenki-effekta.md).
- Ответственные за измерения со стороны Школы: ________ (роли — файл
  02-protokol-izmereniy.md).
- Ответственный Оператора: ________.

Подписи: Школа ________ дата ____ | Оператор ________ дата ____
"""


def _protokol() -> str:
    readiness = SHADOW_GATE_READINESS
    return f"""# Протокол измерений школьной столовой (ШАБЛОН для этапа 5b)

> Каждая страница заполнения — запись контракта данных (docs/DATA_CONTRACT.md).
> Канонические шаблоны: templates/sessions.csv, templates/observations.csv.
> Время — локальное с явной зоной (для КЗ: Asia/Almaty); массы — ТОЛЬКО граммы.

## 1. Роли
- Руководитель измерений (Школа): контроль, сверка еженедельно.
- Оператор взвешивания: ________ (1 человек, сменный — не совмещать с раздачей).
- Оператор данных: вносит записи в CSV в день измерения (recorded_at >= observed_at).

## 2. Оборудование
- Весы кухонные с функцией тарирования, дискретность ≤ 5 г, поверенные.
- Тарированные ёмкости: для производственных отходов, отходов раздачи,
  отходов с тарелок — РАЗНЫЕ, промаркированные.
- Журнал бракеража (по формам Приложения 9 Санитарных правил РК).

## 3. Процедура на каждый обед (LUNCH)
1. Зафиксировать: дату, меню (названия блюд по меню-раскладке), плановое
   число питающихся.
2. ПОСЛЕ готовки: взвесить производственные отходы (production_waste_g)
   по каждому блюду (тара минус).
3. ПОСЛЕ раздачи: взвесить невыданные остатки в мармитах (serving_waste_g).
   prepared_mass_g = заготовка по меню-раскладке (или фактическое взвешивание
   котла, если возможно); served_mass_g = prepared − production − serving
   по каждому блюду; расхождение документировать в notes, не исправлять молча.
4. СТОЛЫ: собрать отходы с тарелок учеников в отдельную ёмкость
   (plate_waste_g). Не смешивать с производственными. По возможности —
   раздельно избегаемые/неизбегаемые (avoidable_waste_g, avoidability_status).
5. Счётчики: meals_served — число фактических выдач (по журналу/электронному
   учёту); attendance_count — число учеников в столовой. meals_requested
   заполняется ТОЛЬКО если есть предзаказ; иначе пусто.
6. Цензурирование спроса: если еда закончилась и кто-то не получил обед —
   demand_censored=true (пропуск ≠ нулевому спросу!). Если закончилась не вся
   еда и все желающие поели — false. Не уверены — unknown.
7. Пустое поле = «не измеряли». НЕ ставить 0 вместо отсутствия измерения.

## 4. Календарь фаз (ворота Системы)
- CALIBRATION, 2 недели: отладка процедуры, обучение операторов. Данные идут
  в хранилище с study_phase=CALIBRATION.
- BASELINE, не менее N недель (N — из плана эффекта, файл 04): «готовим как
  обычно». Вход в фазу — через Систему с protocol_ref (ссылкой на ЭТОТ
  подписанный протокол) — иначе Система отклонит переход.
- SHADOW: Система считает прогнозы/сценарии и копит SHADOW-записи; вход — при
  достаточности данных: min_train={readiness["min_train"]}, calib_days={readiness["calib_days"]}, test_days={readiness["test_days"]} (стартовые
  инженерные пороги; финальные — в утверждённом протоколе этапа 5).
- INTERVENTION и FOLLOWUP — только после выполнения всех условий файла 03.
Дни без обедов (праздники, каникулы) — просто отсутствуют в данных.

## 5. Контроль качества
- Еженедельная сверка: сумма блюд дня == итоги дневника; выбросы (> 3σ от
  медианы той же фазы) — проверять руками до внесения.
- Дубликаты запрещены (Система отклонит): исправления — через ревизию записей.
"""


def _cheklist() -> str:
    conditions = "\n".join(f"- [ ] {c}" for c in INTERVENTION_CONDITIONS)
    return f"""# Чек-лист ворот до вмешательства (заполняет Оператор + Школа)

Условия сформулированы в коде (sra/phases.py: INTERVENTION_CONDITIONS) и
проверяются Системой автоматически, где это возможно. Список ниже — рабочая
копия для людей; Система НЕ примет переход в INTERVENTION/FOLLOWUP, пока
условия не выполнены, и вернёт код E_INTERVENTION_BLOCKED_STAGE5 со списком.

{conditions}

Дополнительно (организационное, вне автоматических проверок):
- [ ] назначен уполномоченный, имеющий право одобрять конкретную версию
      предложения (одобрение привязано к хэшу содержимого);
- [ ] школа понимает: SHADOW-предложения НИКОГДА не исполняются — это
      симуляция сценариев; исполнение — отдельный документ.

Решение при невыполнении хотя бы одного условия — NO_CHANGE с причиной
и списком недостающего (это нормальный, ожидаемый результат Системы).
"""


def _plan_effekta() -> str:
    designs = ", ".join(DESIGNS)
    return f"""# План оценки эффекта (ШАБЛОН; утверждается до BASELINE)

## 1. Метрика эффекта
Первичная: средние отходы с тарелок на едока (г/едока/день), агрегат
Σотходы/Σедоки за фазу (числители/знаменатели агрегируются, проценты не
усредняются). Вторичные: UneatenIndex, WastePerMeal, ServiceLevel — по
отчётам Системы с указанием статуса (COMPUTED/UNAVAILABLE с причиной).

## 2. Дизайн эксперимента
Поддерживаемые дизайны: {designs}.
- before_after (paired): та же школа, BASELINE vs INTERVENTION; n — пары дней.
- two_arm: две сопоставимые группы дней/линий раздачи; n — на группу.

Размер выборки: n = k·(z_{{1−α/2}}+z_power)²·σ²/effect², k=1 (paired) или 2.
Параметры σ (дневная изменчивость) и базовая линия берутся ИЗ ДАННЫХ
CALIBRATION/BASELINE школы, не из литературы.

## 3. Справочные ориентиры (ЧУЖИЕ измерения; НЕ переносить как ожидания)
Класс источника EMPIRICAL_STUDY — другая страна, другая кухня:
- Финляндия (Zenodo 20825233): σ дневного отхода на едока = 8.25 г;
  baseline 23.33 г/едока; эффект их вмешательства ≈ −17 %, но 20 дней
  интервенции — мало (наш расчёт: нужно ~65 дней/группу для такого эффекта
  при α=0.05, power=0.80);
- Латвия (Zenodo 18441715, CC BY 4.0): UneatenIndex 12.7–17.6 % за неделю
  (4 школы, 1–7 классы, pre-served);
- Италия (Sustainability 17(17):7836, 78 школ): отходы тарелок ≈ 90 г/день/
  ребёнка (обед с хлебом/фруктом).
Нормативы порций для сверки полноты: NORM_KZ — Приложение 7 Санправил РК
(приказ ҚР ДСМ-98/2020): первое 200–250 г, гарнир 100–150 г, мясо/рыба
80–150 г, салат 60–100 г (6–11 лет).

## 4. Критерии остановки пилота
- Данные не собираются 5 учебных дней подряд без объяснимой причины.
- Доля дней с цензурированием > 20 %: методика учёта спроса пересматривается.
- Любое давление на персонал «получить эффект» — остановка (искажение данных).

## 5. Что НЕ заявляется до завершения плана
- Точность прогнозов (нет данных — есть только код и его проверки).
- Экономический эффект (считается только по VERIFIED-данным через
  savings-ledger AVF→AOS→BS→VRS с условными переходами).
Статусы различаются всегда: «код готов» ≠ «пилот готов» ≠ «эффект доказан».
"""


def _pamyatka() -> str:
    return """# Памятка: что означает NO_CHANGE

Если Система отвечает NO_CHANGE («изменений не предлагается»), это:
- НЕ «всё хорошо/проблем нет» — Система не оценивала безопасность текущей
  практики;
- ожидаемый ответ, пока не выполнены условия ворот (согласие, проверенный
  протокол, проверенные политики, одобренный план, уполномоченный);
- всегда содержит причину и список недостающего — используйте его как
  план подготовки.

Почему так: вмешательство в работу кухни — решение людей с ответственностью,
а не программы. Система отвечает за то, чтобы предложения были проверяемыми,
а отказ — безопасным и объяснённым.
"""


BUILDERS = {
    "01-soglasie-shkoly.md": _soglasie,
    "02-protokol-izmereniy.md": _protokol,
    "03-cheklist-vorot.md": _cheklist,
    "04-plan-ocenki-effekta.md": _plan_effekta,
    "05-pamyatka-no-change.md": _pamyatka,
}


def build_package(out_dir: str | Path) -> dict:
    """Пишет документы пакета в out_dir. Детерминирован (одинаковый вывод)."""
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    written = []
    for name, builder in BUILDERS.items():
        path = out / name
        path.write_text(builder(), encoding="utf-8")
        written.append(str(path))
    return {"status": "OK", "out_dir": str(out), "files": written,
            "note": ("шаблоны требуют юридической сверки; числа из чужих "
                     "исследований помечены и не переносимы на школу КЗ")}
